"""Generate an English explanation of a route already selected by Python.

The LLM does not select a route. It explains the supplied decision using
factual values from the initial Theta* planned routes.

Place in: USV_LLM_Research/code/generate_route_explanation_en.py
Run:      python code\\generate_route_explanation_en.py --scenario crossing_fore130_u5 --objective distance_priority --prompt p1
Preview:  python code\\generate_route_explanation_en.py --scenario crossing_fore130_u5 --objective distance_priority --prompt p2 --preview
"""

from __future__ import annotations

import argparse
import json
import math
import time
from datetime import datetime
from pathlib import Path

DEFAULT_SCENARIO_ID = "crossing_all130_u5"
DEFAULT_MODEL = "qwen2.5-0.5b-instruct-q4_k_m.gguf"
OBJECTIVES = ("distance_priority", "separation_priority")

# Keep the same inference settings for the first English comparison.
N_CTX = 2048
N_GPU_LAYERS = 0
N_THREADS = 4
MAX_TOKENS = 256
TEMPERATURE = 0.0
PROMPT_VERSIONS = {
    "p1": "objective_baseline_en_v1",
    "p2": "objective_structured_en_v2",
}


def project_root() -> Path:
    """Find the project root when this script is stored in code/."""
    here = Path(__file__).resolve()
    if here.parent.name == "code":
        return here.parent.parent
    return Path.cwd()


def require_number(value: object, label: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (float, int)):
        raise ValueError(f"{label} must be numeric: {value!r}")
    number = float(value)
    if not math.isfinite(number):
        raise ValueError(f"{label} must be finite")
    return number


def load_input(path: Path, objective: str, scenario_id: str) -> dict:
    if not path.is_file():
        raise FileNotFoundError(
            f"English LLM input JSON not found: {path}\n"
            "Run prepare_llm_inputs_en.py first to create the *_llm_input_en.json files."
        )
    with path.open(encoding="utf-8") as stream:
        data = json.load(stream)
    if data.get("scenario_id") != scenario_id:
        raise ValueError(f"Unexpected scenario ID: {data.get('scenario_id')!r}")
    if data.get("language") != "en":
        raise ValueError("This script requires an English-language input JSON")
    if data.get("navigation_objective", {}).get("id") != objective:
        raise ValueError("The input objective does not match --objective")
    if data.get("selected_route") not in ("A", "B"):
        raise ValueError("A unique route A/B must already be selected by Python")
    routes = data.get("routes", {})
    for rid in ("A", "B"):
        info = routes.get(rid)
        if not isinstance(info, dict):
            raise ValueError(f"Missing route {rid} data")
        for field in ("route_length_m", "estimated_travel_time_s", "minimum_separation_m"):
            require_number(info.get(field), f"Route {rid}.{field}")
        if info.get("bypass_side") not in ("starboard side", "port side", "approximately straight", "both sides"):
            raise ValueError(f"Invalid bypass side for route {rid}: {info.get('bypass_side')!r}")
    return data


def route_text(rid: str, data: dict) -> str:
    """Supply factual route values, without calculating differences or writing a reason."""
    route = data["routes"][rid]
    return (
        f"Route {rid}:\n"
        f"  Planned route length: {route['route_length_m']:.2f} m\n"
        f"  Estimated travel time: {route['estimated_travel_time_s']:.2f} s\n"
        f"  Minimum vessel separation: {route['minimum_separation_m']:.2f} m\n"
        f"  Bypass side: {route['bypass_side']}"
    )


def build_prompt(data: dict, prompt_style: str = "p1") -> str:
    """Keep factual inputs constant; change only the explanation instructions."""
    objective = data["navigation_objective"]
    facts = (
        "The following data describe two candidate initial routes generated by Theta* for a small USV.\n"
        "Python has already selected one route based on the stated navigation objective.\n\n"
        f"Navigation objective: {objective['label']}\n"
        f"Selection rule: {objective['rule']}\n"
        f"Already selected route: {data['selected_route']}\n\n"
        f"{route_text('A', data)}\n\n{route_text('B', data)}\n\n"
    )
    # P1 stays byte-for-byte equivalent to the original experiment's prompt.
    p1_instructions = (
        "Explain in English, in 2 or 3 short sentences, why the already selected route meets the objective.\n"
        "Use the actual route A and B values and prioritize the metric relevant to the objective.\n"
        "Do not reselect a route or confuse route length with minimum separation.\n"
        "Bypass side is relative to the own ship's initial heading, not the passing side of the other ship.\n"
        "Do not invent safety thresholds, Bumper validation, COLREG compliance, or unsupported risk claims.\n"
        "Output only the explanation, without repeating these instructions."
    )
    # P2 changes instructions only: same route data, model, and decoding parameters.
    p2_instructions = (
        "Explain in English, in 2 or 3 short sentences, why the already selected route meets the objective.\n"
        "Follow these reasoning steps in order when writing the explanation:\n"
        "1. Identify the already selected route and the single metric specified by the selection rule.\n"
        "2. Quote the values of that metric for BOTH route A and route B, and correctly compare their sizes.\n"
        "3. Explain why that comparison supports the already selected route under the stated objective.\n"
        "If you mention other metrics, compare them correctly and do not use them as the selection criterion.\n"
        "Do not reselect a route or confuse route length with minimum separation.\n"
        "Bypass side is relative to the own ship's initial heading, not the passing side of the other ship.\n"
        "Do not invent safety thresholds, Bumper validation, COLREG compliance, or unsupported risk claims.\n"
        "Output only the explanation, without repeating these instructions or listing the steps."
    )
    if prompt_style == "p1":
        return facts + p1_instructions
    if prompt_style == "p2":
        return facts + p2_instructions
    raise ValueError(f"Unknown prompt style: {prompt_style}")


def model_path(root: Path, value: str) -> Path:
    path = Path(value)
    return path.resolve() if path.is_absolute() else (root / "models" / path).resolve()


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate an English explanation of Python's selected route")
    parser.add_argument("--scenario", default=DEFAULT_SCENARIO_ID,
                        help="Scenario ID used in the saved LLM input filenames")
    parser.add_argument("--objective", choices=OBJECTIVES, default="distance_priority",
                        help="Navigation objective (default: distance_priority)")
    parser.add_argument("--model", default=DEFAULT_MODEL,
                        help="GGUF filename under models/ or an absolute path")
    parser.add_argument("--preview", action="store_true", help="Print the prompt without loading the LLM")
    parser.add_argument("--prompt", choices=PROMPT_VERSIONS, default="p1",
                        help="Explanation instruction style: p1 (baseline) or p2 (structured)")
    parser.add_argument("--project-root", type=Path, default=None, help=argparse.SUPPRESS)
    args = parser.parse_args()

    root = args.project_root.resolve() if args.project_root else project_root()
    # Restrict the identifier to simple filename-safe characters.
    if not args.scenario or any(not (c.isalnum() or c in "-_") for c in args.scenario):
        parser.error("--scenario must contain only letters, digits, underscores, or hyphens")
    input_path = root / "data" / "llm_inputs" / f"{args.scenario}_{args.objective}_llm_input_en.json"
    data = load_input(input_path, args.objective, args.scenario)
    prompt = build_prompt(data, args.prompt)

    print(f"Scenario: {data['scenario_id']}")
    print(f"Navigation objective: {data['navigation_objective']['label']}")
    print(f"Route selected by Python: {data['selected_route']}")
    print(f"Input JSON: {input_path}")
    print(f"Prompt: {args.prompt} ({PROMPT_VERSIONS[args.prompt]})")

    if args.preview:
        print("\n=== LLM prompt preview ===")
        print(prompt)
        print("\nPreview only: no inference and no result file written.")
        return

    gguf = model_path(root, args.model)
    if not gguf.is_file():
        raise FileNotFoundError(f"GGUF model not found: {gguf}")
    try:
        from llama_cpp import Llama
    except ImportError as exc:
        raise RuntimeError("llama-cpp-python is unavailable in the active Python environment") from exc

    print(f"Model: {gguf.name}")
    print("Loading model...")
    llm = Llama(model_path=str(gguf), n_ctx=N_CTX,
                n_gpu_layers=N_GPU_LAYERS, n_threads=N_THREADS, verbose=False)

    started = time.perf_counter()
    response = llm.create_chat_completion(
        messages=[
            {"role": "system", "content": "You explain a USV route-selection result using only the supplied facts. Write in clear, concise English."},
            {"role": "user", "content": prompt},
        ],
        max_tokens=MAX_TOKENS,
        temperature=TEMPERATURE,
        top_p=1.0,
    )
    elapsed = time.perf_counter() - started

    choice = response["choices"][0]
    explanation = (choice.get("message", {}).get("content") or "").strip()
    if not explanation:
        print("Warning: the generated explanation is empty.")
    print("\n=== Generated explanation ===")
    print(explanation or "(empty)")
    print(f"Inference time: {elapsed:.2f} s")
    print(f"Finish reason: {choice.get('finish_reason', 'unknown')}")

    output_dir = root / "results" / "llm_explanations"
    output_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S_%f")
    output_path = output_dir / f"{args.scenario}_{args.objective}_{gguf.stem}_en_{args.prompt}_{timestamp}.json"
    record = {
        "timestamp": datetime.now().astimezone().isoformat(),
        "language": "en",
        "scenario_id": data["scenario_id"],
        "objective_id": args.objective,
        "selected_route_by_python": data["selected_route"],
        "model_file": gguf.name,
        "prompt_version": PROMPT_VERSIONS[args.prompt],
        "prompt_style": args.prompt,
        "parameters": {
            "n_ctx": N_CTX,
            "n_gpu_layers": N_GPU_LAYERS,
            "n_threads": N_THREADS,
            "max_tokens": MAX_TOKENS,
            "temperature": TEMPERATURE,
            "top_p": 1.0,
        },
        "input_file": str(input_path.relative_to(root)),
        "prompt": prompt,
        "generated_explanation": explanation,
        "inference_seconds": round(elapsed, 4),
        "finish_reason": choice.get("finish_reason"),
        "token_usage": response.get("usage", {}),
        "evaluation_status": "not_evaluated",
    }
    # Exclusive creation protects the previous runs.
    with output_path.open("x", encoding="utf-8") as stream:
        json.dump(record, stream, ensure_ascii=False, indent=2)
        stream.write("\n")
    print(f"Result saved: {output_path}")
    print("Explanation quality has not been evaluated yet.")


if __name__ == "__main__":
    main()
